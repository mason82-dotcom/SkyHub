#!/bin/sh
set -eu

project_dir=$(CDPATH= cd -- "$(dirname -- "$0")/.." && pwd)
env_file="$project_dir/.env"
backup_dir="$project_dir/.skyhub-env-backups"

if ! command -v openssl >/dev/null 2>&1; then
    echo "Fehler: openssl wird zur sicheren Schlüsselerzeugung benötigt." >&2
    exit 1
fi

detect_lan_ip() {
    if command -v ip >/dev/null 2>&1; then
        ip -4 route get 1.1.1.1 2>/dev/null \
            | awk '{ for (i = 1; i <= NF; i++) if ($i == "src") { print $(i + 1); exit } }'
    fi
}

secret() {
    openssl rand -hex 32
}

lan_ip=$(detect_lan_ip)
lan_ip=${lan_ip:-127.0.0.1}
umask 077
mkdir -p "$backup_dir"

if [ -f "$env_file" ]; then
    backup_file="$backup_dir/env-$(date -u +%Y%m%dT%H%M%SZ)"
    cp "$env_file" "$backup_file"
    chmod 600 "$backup_file"
fi

temp_file=$(mktemp "$project_dir/.env.tmp.XXXXXX")
trap 'rm -f "$temp_file"' EXIT HUP INT TERM

{
    printf '%s\n' "# Generated by scripts/migrate-env.sh. Keep this file private."
    printf 'POSTGRES_PASSWORD=%s\n' "$(secret)"
    printf 'REDIS_PASSWORD=%s\n' "$(secret)"
    printf 'MQTT_CORE_PASSWORD=%s\n' "$(secret)"
    printf 'MQTT_GATEWAY_PASSWORD=%s\n' "$(secret)"
    printf 'EMQX_NODE_COOKIE=%s\n' "$(secret)"
    printf 'EMQX_DASHBOARD_PASSWORD=%s\n' "$(secret)"
    printf '%s\n' 'PILOT_USERNAME=pilot'
    printf 'PILOT_PASSWORD=%s\n' "$(secret)"
    printf 'SKYHUB_ADMIN_TOKEN=%s\n' "$(secret)"
    printf 'SKYHUB_LAN_IP=%s\n' "$lan_ip"
    printf '%s\n' 'MISSION_DISPATCH_ENABLED=false'
    printf '%s\n' 'MISSION_FILE_ALLOWED_ORIGINS='
} > "$temp_file"

chmod 600 "$temp_file"
mv "$temp_file" "$env_file"
trap - EXIT HUP INT TERM

echo "SkyHub-Konfiguration migriert. Alte Konfiguration liegt geschützt unter .skyhub-env-backups/."
echo "LAN-Adresse: $lan_ip"
echo "Missionsversand: deaktiviert"
